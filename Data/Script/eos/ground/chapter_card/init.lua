--Engine callback function
function chapter_card.Enter(map)

  ExplorerEssentials.AutosaveWithNotification()

  GAME:CutsceneMode(true)
  GROUND:Hide("PLAYER")

  -- demo end check
  if SV.Progression.Chapter > 2 then
    SV.Progression.DemoCompleted = true
    GAME:WaitFrames(30)
    UI:ResetSpeaker()
    UI:SetCenter(true)
    UI:WaitShowDialogue(STRINGS:Format(STRINGS.MapStrings['DemoNotification']))
    UI:SetCenter(false)
    GAME:EnterGroundMap("demo_room", "Entrance")
  else

    --everything else goes here

  SV.Progression.DemoCompleted = false

  GAME:FadeIn(60)
  
  local coro1 = TASK:BranchCoroutine(function() UI:WaitShowTitle(STRINGS:Format(STRINGS.MapStrings['ChapterTitle_'..tostring(SV.Progression.Chapter)]), 60)
												  GAME:WaitFrames(300)
												  UI:WaitHideTitle(60) end)
  local coro2 = TASK:BranchCoroutine(function() UI:WaitShowBG("ChapterCard_"..tostring(SV.Progression.Chapter), 1, 60)
												  GAME:WaitFrames(300)
												  UI:WaitHideBG(60) end)
  TASK:JoinCoroutines({coro1, coro2})

  GAME:WaitFrames(60)
  
  if SV.Progression.Chapter == 1 then
	  GAME:EnterGroundMap("storm_cutscene_a", "Entrance")
  elseif SV.Progression.Chapter == 2 then
	  GAME:EnterGroundMap("guild_outside_dusk", "Entrance")
  elseif SV.Progression.Chapter >= 3 and SV.Progression.Chapter <= 6 then
	  GAME:EnterGroundMap("hub", "guild_bedroom", "Entrance", false)
  else
	  --progression broke you aren't supposed to be here
	  UI:WaitShowDialogue(STRINGS:Format("If you're currently reading this, the game's progression system has broken somehow. You should probably tell Mocha about this. Going to title screen now."))
	  GAME:RestartToTitle()
  end


  end
end

